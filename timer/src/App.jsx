import { useState } from "react";
import Timer from "./Timer";

function App() {
  const [showTimer, setShowTimer] = useState(false);

  function handleToggleTimer() {
    setShowTimer(prev => !prev);
  }

  return (
    <div>
      <button onClick={handleToggleTimer}>
        {showTimer ? "Timer 숨기기" : "Timer 표시"}
      </button>

      {showTimer === true && <Timer />}
    </div>
  );
}

export default App;

// Conditional Rendering은 조건에 따라 컴포넌트를 렌더링하는 방식입니다.
// showTimer가 true로 바뀌면 Timer가 화면에 추가되면서 Mount됩니다.
// showTimer가 false로 바뀌면 Timer가 제거되면서 Unmount됩니다.
//
// Unmount 시 Timer의 useEffect에서 반환한 Cleanup 함수가 실행됩니다.
// 기존 clearInterval(intervalId)이 호출되어 실행 중인 interval도 정리됩니다.
//
// 다시 표시하면 새로운 Timer가 Mount되므로
// seconds는 0, isRunning은 false로 초기화됩니다.












